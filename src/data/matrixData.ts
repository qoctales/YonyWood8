// FONCTION UNIVERSELLE : RÉCUPÉRER EXACTEMENT 16 PROTAGONISTES PAR SÉRIE
// =========================================================================
export function get16ProtagonistsForSeries(
  series: MatrixSeriesConfig,
  topicId: string,
  shuffleSeed: number = 0
): AffiliationPerson[] {
  const allPeople: AffiliationPerson[] = [];
  const seenIds = new Set<string>();

  function collect(arr?: AffiliationPerson[]) {
    if (!arr) return;
    for (const p of arr) {
      if (!seenIds.has(p.id)) {
        seenIds.add(p.id);
        allPeople.push(p);
      }
      if (p.invitedPeople && p.invitedPeople.length > 0) {
        collect(p.invitedPeople);
      }
    }
  }

  collect(series?.pioneers);

  if (allPeople.length < 16) {
    const fallbacks = get16StoriesForTopic(topicId, shuffleSeed);
    for (const fb of fallbacks) {
      if (allPeople.length >= 16) break;
      if (!seenIds.has(fb.id)) {
        seenIds.add(fb.id);
        allPeople.push(fb);
      }
    }
  }

  const offset = (shuffleSeed * 3) % Math.max(1, allPeople.length);
  const rotated = [...allPeople.slice(offset), ...allPeople.slice(0, offset)];
  return rotated.slice(0, 16);
}

